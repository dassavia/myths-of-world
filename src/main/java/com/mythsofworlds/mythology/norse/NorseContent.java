package com.mythsofworlds.mythology.norse;

import com.mythsofworlds.MythsOfWorlds;
import com.mythsofworlds.core.portal.MythPortalBlock;
import com.mythsofworlds.core.portal.PortalIgniterItem;
import com.mythsofworlds.core.portal.PortalSettings;
import com.mythsofworlds.journal.JournalItem;
import com.mythsofworlds.mythology.greek.block.FruitLeavesBlock;
import com.mythsofworlds.mythology.norse.item.GleipnirItem;
import com.mythsofworlds.mythology.norse.item.MjolnirItem;
import com.mythsofworlds.mythology.norse.item.SurtrSwordItem;
import com.mythsofworlds.registry.MetalSet;
import java.util.List;
import net.minecraft.core.particles.ParticleTypes;
import net.minecraft.core.registries.Registries;
import net.minecraft.resources.ResourceKey;
import net.minecraft.sounds.SoundEvents;
import net.minecraft.util.valueproviders.UniformInt;
import net.minecraft.world.effect.MobEffectInstance;
import net.minecraft.world.effect.MobEffects;
import net.minecraft.world.food.FoodProperties;
import net.minecraft.world.item.BlockItem;
import net.minecraft.world.item.HoneyBottleItem;
import net.minecraft.world.item.Item;
import net.minecraft.world.item.Items;
import net.minecraft.world.item.Rarity;
import net.minecraft.world.item.SwordItem;
import net.minecraft.world.item.Tiers;
import net.minecraft.world.level.Level;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.DropExperienceBlock;
import net.minecraft.world.level.block.LeavesBlock;
import net.minecraft.world.level.block.RotatedPillarBlock;
import net.minecraft.world.level.block.SoundType;
import net.minecraft.world.level.block.state.BlockBehaviour;
import net.minecraft.world.level.block.state.properties.NoteBlockInstrument;
import net.minecraft.world.level.material.MapColor;
import net.minecraft.world.level.material.PushReaction;
import net.neoforged.neoforge.registries.DeferredBlock;
import net.neoforged.neoforge.registries.DeferredItem;

import static com.mythsofworlds.registry.ModRegistries.BLOCKS;
import static com.mythsofworlds.registry.ModRegistries.ITEMS;

/**
 * Norse mythology: the Bifrost portal to Jotunheim, the land of the giants, with its blocks and the treasures of its
 * gods and monsters. Mobs live in {@link NorseEntities}; biomes, structures and loot are data files generated by
 * tools/gen_norse_assets.py.
 */
public final class NorseContent {
    /** Defined in data/mythsofworlds/dimension/jotunheim.json. */
    public static final ResourceKey<Level> JOTUNHEIM =
            ResourceKey.create(Registries.DIMENSION, MythsOfWorlds.id("jotunheim"));
    /** Biomes of Jotunheim (data/mythsofworlds/worldgen/biome). */
    public static final List<String> BIOMES = List.of("frost_wastes", "giants_taiga", "ironwood", "fjords", "norse_sea",
            "muspel_rift", "niflheim_mists", "idunn_orchard");
    /** Structures of Jotunheim (data/mythsofworlds/worldgen/structure, templates in data/mythsofworlds/structure/norse). */
    public static final List<String> STRUCTURES = List.of("viking_village", "longship", "naglfar", "barrow", "utgard",
            "fenrir_island", "muspel_fortress", "helgrind", "dwarf_forge", "rune_circle", "valkyrie_hall");

    // ---- Blocks ----

    /** Frame block for the Bifrost portal. Its carved runes glow faintly. */
    public static final DeferredBlock<Block> RUNESTONE = BLOCKS.registerSimpleBlock("runestone",
            BlockBehaviour.Properties.of()
                    .mapColor(MapColor.DEEPSLATE)
                    .strength(3.0F, 9.0F)
                    .requiresCorrectToolForDrops()
                    .sound(SoundType.DEEPSLATE_BRICKS)
                    .lightLevel(state -> 3));

    /** Standing stone with runes painted red, raised in memory of heroes. Glows like an ember. */
    public static final DeferredBlock<Block> CARVED_RUNESTONE = BLOCKS.registerSimpleBlock("carved_runestone",
            BlockBehaviour.Properties.of()
                    .mapColor(MapColor.STONE)
                    .strength(3.0F, 9.0F)
                    .requiresCorrectToolForDrops()
                    .sound(SoundType.DEEPSLATE_BRICKS)
                    .lightLevel(state -> 8));

    public static final DeferredBlock<MythPortalBlock> BIFROST_PORTAL = BLOCKS.register("bifrost_portal",
            () -> new MythPortalBlock(
                    PortalSettings.toDimension(RUNESTONE, JOTUNHEIM, ParticleTypes.SNOWFLAKE),
                    BlockBehaviour.Properties.of()
                            .mapColor(MapColor.COLOR_LIGHT_BLUE)
                            .noCollission()
                            .strength(-1.0F)
                            .sound(SoundType.GLASS)
                            .lightLevel(state -> 11)
                            .noLootTable()
                            .pushReaction(PushReaction.BLOCK)));

    private static BlockBehaviour.Properties ironwood() {
        return BlockBehaviour.Properties.of()
                .mapColor(MapColor.COLOR_GRAY)
                .instrument(NoteBlockInstrument.BASS)
                .strength(4.0F, 6.0F)
                .sound(SoundType.WOOD)
                .ignitedByLava();
    }

    /** Wood of Jarnvidr, the Iron Wood where the wolf-mothers of Fenrir's kin live. Harder than any other wood. */
    public static final DeferredBlock<RotatedPillarBlock> IRONWOOD_LOG =
            BLOCKS.registerBlock("ironwood_log", RotatedPillarBlock::new, ironwood());
    public static final DeferredBlock<Block> IRONWOOD_PLANKS = BLOCKS.registerSimpleBlock("ironwood_planks", ironwood());

    private static BlockBehaviour.Properties leaves(MapColor color) {
        return BlockBehaviour.Properties.of()
                .mapColor(color)
                .strength(0.2F)
                .randomTicks()
                .sound(SoundType.GRASS)
                .noOcclusion()
                .isValidSpawn((state, level, pos, type) -> false)
                .isSuffocating((state, level, pos) -> false)
                .isViewBlocking((state, level, pos) -> false)
                .ignitedByLava()
                .pushReaction(PushReaction.DESTROY);
    }

    public static final DeferredBlock<LeavesBlock> IRONWOOD_LEAVES = BLOCKS.register("ironwood_leaves",
            () -> new LeavesBlock(leaves(MapColor.COLOR_GRAY)));
    /** Leaves of the apple trees of Idunn; the golden apples that keep the gods young ripen on them. */
    public static final DeferredBlock<FruitLeavesBlock> IDUNN_LEAVES = BLOCKS.register("idunn_leaves",
            () -> new FruitLeavesBlock(NorseContent.IDUNN_APPLE, leaves(MapColor.PLANT).lightLevel(state -> 3)));

    // ---- Metals and fuel ----

    /** Dark iron of the dwarves of Svartalfheim, deep in the stone of Jotunheim: the toughest of the metals. */
    public static final MetalSet DARK_IRON = new MetalSet("dark_iron", MapColor.COLOR_GRAY, new MetalSet.Stats(
            1900, 7.0F, 3.5F, 12, new int[]{3, 8, 6, 3}, 37, 2.5F, 0.05F, SoundEvents.ARMOR_EQUIP_NETHERITE));
    /** Embers of Muspelheim locked in the stone of the fire rift: they burn three times as long as coal. */
    public static final DeferredBlock<DropExperienceBlock> MUSPEL_EMBER_ORE = BLOCKS.registerBlock("muspel_ember_ore",
            props -> new DropExperienceBlock(UniformInt.of(2, 4), props), BlockBehaviour.Properties.of()
                    .mapColor(MapColor.COLOR_RED).strength(3.0F, 3.0F).requiresCorrectToolForDrops().lightLevel(state -> 7));
    public static final DeferredItem<BlockItem> MUSPEL_EMBER_ORE_ITEM = ITEMS.registerSimpleBlockItem(MUSPEL_EMBER_ORE);

    // ---- Items ----

    public static final DeferredItem<BlockItem> RUNESTONE_ITEM = ITEMS.registerSimpleBlockItem(RUNESTONE);
    public static final DeferredItem<BlockItem> CARVED_RUNESTONE_ITEM = ITEMS.registerSimpleBlockItem(CARVED_RUNESTONE);
    public static final DeferredItem<BlockItem> IRONWOOD_LOG_ITEM = ITEMS.registerSimpleBlockItem(IRONWOOD_LOG);
    public static final DeferredItem<BlockItem> IRONWOOD_PLANKS_ITEM = ITEMS.registerSimpleBlockItem(IRONWOOD_PLANKS);
    public static final DeferredItem<BlockItem> IRONWOOD_LEAVES_ITEM = ITEMS.registerSimpleBlockItem(IRONWOOD_LEAVES);
    public static final DeferredItem<BlockItem> IDUNN_LEAVES_ITEM = ITEMS.registerSimpleBlockItem(IDUNN_LEAVES);

    public static final DeferredItem<PortalIgniterItem> RUNE_IGNITER = ITEMS.register("rune_igniter",
            () -> new PortalIgniterItem(new Item.Properties().durability(16).rarity(Rarity.RARE),
                    () -> SoundEvents.BEACON_ACTIVATE, List.of(BIFROST_PORTAL)));

    /** Skald's journal: records every creature and place of Jotunheim the player has found. */
    public static final DeferredItem<JournalItem> NORSE_JOURNAL = ITEMS.register("norse_journal",
            () -> new JournalItem("norse", false, new Item.Properties().stacksTo(1)));
    /** Creative-only copy of the journal with every entry already written. */
    public static final DeferredItem<JournalItem> NORSE_JOURNAL_COMPLETE = ITEMS.register("norse_journal_complete",
            () -> new JournalItem("norse", true, new Item.Properties().stacksTo(1).rarity(Rarity.EPIC)));

    /** Golden apple of Idunn: the gods eat them to stay young. Heals and strengthens the heart. */
    public static final DeferredItem<Item> IDUNN_APPLE = ITEMS.registerItem("idunn_apple", props -> new Item(props
            .rarity(Rarity.UNCOMMON)
            .food(new FoodProperties.Builder()
                    .nutrition(5)
                    .saturationModifier(1.0F)
                    .alwaysEdible()
                    .effect(new MobEffectInstance(MobEffects.REGENERATION, 160, 1), 1.0F)
                    .effect(new MobEffectInstance(MobEffects.HEALTH_BOOST, 2400, 0), 1.0F)
                    .build())));
    /** Honey mead of the mead halls: courage of the berserkers, and a spinning head. */
    public static final DeferredItem<HoneyBottleItem> MEAD = ITEMS.register("mead",
            () -> new HoneyBottleItem(new Item.Properties()
                    .craftRemainder(Items.GLASS_BOTTLE)
                    .stacksTo(16)
                    .food(new FoodProperties.Builder()
                            .nutrition(4)
                            .saturationModifier(0.4F)
                            .alwaysEdible()
                            .effect(new MobEffectInstance(MobEffects.DAMAGE_BOOST, 1200, 0), 1.0F)
                            .effect(new MobEffectInstance(MobEffects.DAMAGE_RESISTANCE, 1200, 0), 1.0F)
                            .effect(new MobEffectInstance(MobEffects.CONFUSION, 160, 0), 0.5F)
                            .build())));

    // Trophies dropped by the giants and monsters of Jotunheim.
    public static final DeferredItem<Item> RAVEN_FEATHER = ITEMS.registerSimpleItem("raven_feather");
    public static final DeferredItem<Item> FROST_HEART = ITEMS.registerSimpleItem("frost_heart",
            new Item.Properties().rarity(Rarity.UNCOMMON));
    public static final DeferredItem<Item> MUSPEL_EMBER = ITEMS.registerSimpleItem("muspel_ember",
            new Item.Properties().rarity(Rarity.UNCOMMON).fireResistant());
    public static final DeferredItem<Item> TROLL_TUSK = ITEMS.registerSimpleItem("troll_tusk",
            new Item.Properties().rarity(Rarity.UNCOMMON));
    public static final DeferredItem<Item> FENRIR_FANG = ITEMS.registerSimpleItem("fenrir_fang",
            new Item.Properties().rarity(Rarity.RARE));
    public static final DeferredItem<Item> GARM_FANG = ITEMS.registerSimpleItem("garm_fang",
            new Item.Properties().rarity(Rarity.RARE));
    /** Crown of a barrow-king, taken from the Draugr chieftain. */
    public static final DeferredItem<Item> BARROW_CROWN = ITEMS.registerSimpleItem("barrow_crown",
            new Item.Properties().stacksTo(1).rarity(Rarity.RARE));

    /** Thor's hammer, stolen by Thrym, king of the frost giants. Calls down lightning where you point it. */
    public static final DeferredItem<MjolnirItem> MJOLNIR = ITEMS.register("mjolnir",
            () -> new MjolnirItem(new Item.Properties().rarity(Rarity.EPIC).durability(400)
                    .attributes(SwordItem.createAttributes(Tiers.NETHERITE, 7, -3.0F))));
    /** The dwarf-made ribbon that bound Fenrir: use it on the wolf to hold him fast for a while. */
    public static final DeferredItem<GleipnirItem> GLEIPNIR = ITEMS.register("gleipnir",
            () -> new GleipnirItem(new Item.Properties().rarity(Rarity.EPIC).durability(4)));
    /** Flaming sword of Surtr, lord of Muspelheim. Sets whatever it strikes on fire. */
    public static final DeferredItem<SurtrSwordItem> SURTR_SWORD = ITEMS.register("surtr_sword",
            () -> new SurtrSwordItem(new Item.Properties().rarity(Rarity.EPIC).fireResistant()
                    .attributes(SwordItem.createAttributes(Tiers.NETHERITE, 4, -2.4F))));

    private NorseContent() {
    }

    /** Called from the mod constructor so the fields above are registered. */
    public static void init() {
    }
}
