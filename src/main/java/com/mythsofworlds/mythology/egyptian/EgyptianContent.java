package com.mythsofworlds.mythology.egyptian;

import com.mythsofworlds.MythsOfWorlds;
import com.mythsofworlds.mythology.Mythology;
import com.mythsofworlds.mythology.egyptian.block.PyramidGateBlock;
import com.mythsofworlds.mythology.egyptian.item.AnkhItem;
import com.mythsofworlds.mythology.egyptian.item.KhopeshItem;
import com.mythsofworlds.mythology.egyptian.item.WasSceptreItem;
import com.mythsofworlds.mythology.greek.block.FruitLeavesBlock;
import com.mythsofworlds.mythology.greek.item.HornOfThemiscyraItem;
import com.mythsofworlds.mythology.relic.RelicArmorItem;
import com.mythsofworlds.registry.MetalSet;
import java.util.List;
import net.minecraft.core.registries.Registries;
import net.minecraft.resources.ResourceKey;
import net.minecraft.sounds.SoundEvents;
import net.minecraft.tags.BlockTags;
import net.minecraft.tags.TagKey;
import net.minecraft.world.effect.MobEffectInstance;
import net.minecraft.world.effect.MobEffects;
import net.minecraft.world.food.FoodProperties;
import net.minecraft.world.item.ArmorItem;
import net.minecraft.world.item.ArmorMaterial;
import net.minecraft.world.item.BlockItem;
import net.minecraft.world.item.Item;
import net.minecraft.world.item.Items;
import net.minecraft.world.item.Rarity;
import net.minecraft.world.item.SwordItem;
import net.minecraft.world.item.crafting.Ingredient;
import net.minecraft.world.level.Level;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.SoundType;
import net.minecraft.world.level.block.state.BlockBehaviour;
import net.minecraft.world.level.levelgen.structure.Structure;
import net.minecraft.world.level.material.MapColor;
import net.minecraft.world.level.material.PushReaction;
import net.neoforged.neoforge.registries.DeferredBlock;
import net.neoforged.neoforge.registries.DeferredHolder;
import net.neoforged.neoforge.registries.DeferredItem;

import static com.mythsofworlds.registry.ModRegistries.BLOCKS;
import static com.mythsofworlds.registry.ModRegistries.ITEMS;

/**
 * Egyptian mythology: the Duat, the desert of everlasting night that the barque of Ra crosses between sunset and
 * dawn. The way there is a pyramid: build one of pyramid stone with a golden capstone, leave a doorway in its base and
 * touch it with the ankh, and a gate of shadow opens in the doorway (see {@link com.mythsofworlds.mythology.egyptian.block.Pyramid}).
 * Mobs live in {@link EgyptianEntities}; biomes, structures and loot are data files generated by
 * tools/gen_egyptian_assets.py.
 */
public final class EgyptianContent {
    /** Defined in data/mythsofworlds/dimension/duat.json. */
    public static final ResourceKey<Level> DUAT =
            ResourceKey.create(Registries.DIMENSION, MythsOfWorlds.id("duat"));
    /** Biomes of the Duat (data/mythsofworlds/worldgen/biome). */
    public static final List<String> BIOMES = List.of("duat_sands", "nile_banks", "fields_of_aaru", "valley_of_kings",
            "lake_of_fire", "oasis", "celestial_nile");
    /** Structures of the Duat (data/mythsofworlds/worldgen/structure, templates in data/mythsofworlds/structure/egyptian). */
    public static final List<String> STRUCTURES = List.of("egyptian_village", "temple_of_isis", "obelisk", "pharaoh_tomb",
            "great_sphinx", "temple_of_set", "apep_lair");
    /** The temples of Isis, where the priestesses live; the sistrum of Hathor calls them back there. */
    public static final TagKey<Structure> PRIESTESS_HOMES = TagKey.create(Registries.STRUCTURE, MythsOfWorlds.id("priestess_homes"));

    // ---- Blocks ----

    private static BlockBehaviour.Properties stone(MapColor color) {
        return BlockBehaviour.Properties.of().mapColor(color).strength(1.5F, 6.0F).requiresCorrectToolForDrops()
                .sound(SoundType.STONE);
    }

    /** Smooth golden-white limestone the pyramids are faced with; their base and steps are built of it. */
    public static final DeferredBlock<Block> PYRAMID_STONE = BLOCKS.registerSimpleBlock("pyramid_stone", stone(MapColor.SAND));
    /** Pyramid stone carved with hieroglyphs: it counts as pyramid stone too. */
    public static final DeferredBlock<Block> HIEROGLYPH_STONE = BLOCKS.registerSimpleBlock("hieroglyph_stone",
            stone(MapColor.SAND));
    /** The gate of shadow in the doorway of a pyramid: stand in it three seconds to pass into the Duat (or back). */
    public static final DeferredBlock<PyramidGateBlock> PYRAMID_GATE = BLOCKS.register("pyramid_gate",
            () -> new PyramidGateBlock(BlockBehaviour.Properties.of()
                    .mapColor(MapColor.COLOR_BLACK)
                    .noCollission()
                    .strength(-1.0F)
                    .sound(SoundType.SAND)
                    .lightLevel(state -> 10)
                    .noLootTable()
                    .pushReaction(PushReaction.BLOCK)));

    /** Fronds of the date palm of the Nile; dates ripen among them. */
    public static final DeferredBlock<FruitLeavesBlock> DATE_PALM_LEAVES = BLOCKS.register("date_palm_leaves",
            () -> new FruitLeavesBlock(EgyptianContent.DATES, BlockBehaviour.Properties.of()
                    .mapColor(MapColor.COLOR_GREEN)
                    .strength(0.2F)
                    .randomTicks()
                    .sound(SoundType.GRASS)
                    .noOcclusion()
                    .isValidSpawn((state, level, pos, type) -> false)
                    .isSuffocating((state, level, pos) -> false)
                    .isViewBlocking((state, level, pos) -> false)
                    .ignitedByLava()
                    .pushReaction(PushReaction.DESTROY)));

    public static final DeferredItem<BlockItem> PYRAMID_STONE_ITEM = ITEMS.registerSimpleBlockItem(PYRAMID_STONE);
    public static final DeferredItem<BlockItem> HIEROGLYPH_STONE_ITEM = ITEMS.registerSimpleBlockItem(HIEROGLYPH_STONE);
    public static final DeferredItem<BlockItem> DATE_PALM_LEAVES_ITEM = ITEMS.registerSimpleBlockItem(DATE_PALM_LEAVES);

    // ---- Items ----

    /** The ankh, the key of life: touch a finished pyramid with it to open the gate of shadow. */
    public static final DeferredItem<AnkhItem> ANKH = ITEMS.register("ankh",
            () -> new AnkhItem(new Item.Properties().durability(16).rarity(Rarity.RARE)));
    /** Picked from the fronds of the date palm: sweet and quick to eat. */
    public static final DeferredItem<Item> DATES = ITEMS.registerItem("dates", props -> new Item(props
            .food(new FoodProperties.Builder().nutrition(3).saturationModifier(0.6F).fast().build())));
    /** Bread of the Nile with honey and dates: a feast for the priestesses, and their wedding gift. */
    public static final DeferredItem<Item> HONEY_CAKE = ITEMS.registerItem("honey_cake", props -> new Item(props
            .food(new FoodProperties.Builder().nutrition(9).saturationModifier(0.9F)
                    .effect(new MobEffectInstance(MobEffects.REGENERATION, 100, 0), 1.0F).build())));
    public static final DeferredItem<Item> MUMMY_WRAPPINGS = ITEMS.registerSimpleItem("mummy_wrappings", new Item.Properties());
    public static final DeferredItem<Item> SCARAB_SHELL = ITEMS.registerSimpleItem("scarab_shell",
            new Item.Properties().rarity(Rarity.UNCOMMON));
    public static final DeferredItem<Item> SCORPION_STINGER = ITEMS.registerSimpleItem("scorpion_stinger", new Item.Properties());
    public static final DeferredItem<Item> JACKAL_PELT = ITEMS.registerSimpleItem("jackal_pelt", new Item.Properties());
    public static final DeferredItem<Item> SPHINX_CLAW = ITEMS.registerSimpleItem("sphinx_claw",
            new Item.Properties().rarity(Rarity.RARE));
    public static final DeferredItem<Item> APEP_SCALE = ITEMS.registerSimpleItem("apep_scale",
            new Item.Properties().rarity(Rarity.RARE).fireResistant());
    /** The wedjat, the healed eye of Horus: Set cannot stand against the one who carries it. */
    public static final DeferredItem<Item> EYE_OF_HORUS = ITEMS.registerSimpleItem("eye_of_horus",
            new Item.Properties().stacksTo(1).rarity(Rarity.EPIC));
    /** The tyet, the knot of Isis: it wins the heart of a priestess at once. */
    public static final DeferredItem<Item> KNOT_OF_ISIS = ITEMS.registerSimpleItem("knot_of_isis",
            new Item.Properties().stacksTo(1).rarity(Rarity.EPIC));
    /** The sistrum of Hathor: shaken near a temple of Isis, it calls the priestesses who strayed back home. */
    public static final DeferredItem<HornOfThemiscyraItem> SISTRUM = ITEMS.register("sistrum",
            () -> new HornOfThemiscyraItem(PRIESTESS_HOMES, new Item.Properties().stacksTo(1).rarity(Rarity.UNCOMMON)));

    /** Meteoric iron, the "iron of heaven" (bia-n-pet) that fell into the Duat: the metal of tier II, as strong as
     * diamond, found deep in its stone. */
    public static final MetalSet METEORIC_IRON = new MetalSet("meteoric_iron", MapColor.COLOR_GRAY, new MetalSet.Stats(
            1650, 8.0F, 3.5F, 18, new int[]{3, 8, 6, 3}, 33, 2.0F, 0.0F, SoundEvents.ARMOR_EQUIP_IRON,
            BlockTags.INCORRECT_FOR_DIAMOND_TOOL));

    /** The khopesh of the pharaoh, a sickle-sword of meteoric iron: every blow withers the foe. */
    public static final DeferredItem<KhopeshItem> KHOPESH = ITEMS.register("khopesh",
            () -> new KhopeshItem(METEORIC_IRON.tier, new Item.Properties().rarity(Rarity.EPIC).fireResistant()
                    .attributes(SwordItem.createAttributes(METEORIC_IRON.tier, 4, -2.4F))));
    /** The was-sceptre of Set, lord of storms: raise it and a sandstorm throws back the foes around. */
    public static final DeferredItem<WasSceptreItem> WAS_SCEPTRE = ITEMS.register("was_sceptre",
            () -> new WasSceptreItem(new Item.Properties().durability(250).rarity(Rarity.EPIC).fireResistant()));

    /** The striped nemes of the Sphinx: the eyes of the guardian of the desert see through the night. */
    public static final DeferredHolder<ArmorMaterial, ArmorMaterial> NEMES_MATERIAL = RelicArmorItem.material("nemes",
            ArmorItem.Type.HELMET, 3, 22, SoundEvents.ARMOR_EQUIP_GOLD, () -> Ingredient.of(Items.GOLD_INGOT), 2.0F, 0.0F);
    public static final DeferredItem<RelicArmorItem> NEMES = ITEMS.register("nemes",
            () -> new RelicArmorItem(NEMES_MATERIAL, ArmorItem.Type.HELMET, Mythology.EGYPTIAN, EgyptianRelics::nemes,
                    new Item.Properties().durability(ArmorItem.Type.HELMET.getDurability(30)).rarity(Rarity.EPIC)));
    /** The golden pectoral of Ra with the sun disc, taken from the coils of Apep: the sun's fire cannot burn its bearer. */
    public static final DeferredHolder<ArmorMaterial, ArmorMaterial> PECTORAL_MATERIAL = RelicArmorItem.material("pectoral_of_ra",
            ArmorItem.Type.CHESTPLATE, 8, 22, SoundEvents.ARMOR_EQUIP_GOLD, () -> Ingredient.of(Items.GOLD_INGOT), 2.5F, 0.05F);
    public static final DeferredItem<RelicArmorItem> PECTORAL_OF_RA = ITEMS.register("pectoral_of_ra",
            () -> new RelicArmorItem(PECTORAL_MATERIAL, ArmorItem.Type.CHESTPLATE, Mythology.EGYPTIAN, EgyptianRelics::pectoral,
                    new Item.Properties().durability(ArmorItem.Type.CHESTPLATE.getDurability(33)).rarity(Rarity.EPIC)
                            .fireResistant()));

    private EgyptianContent() {
    }

    /** Called from the mod constructor so the fields above are registered. */
    public static void init() {
    }
}
