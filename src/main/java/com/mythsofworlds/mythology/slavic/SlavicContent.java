import net.neoforged.neoforge.registries.DeferredHolder;
import net.neoforged.neoforge.registries.DeferredItem;

import static com.mythsofworlds.registry.ModRegistries.BLOCKS;
import static com.mythsofworlds.registry.ModRegistries.ITEMS;
import static com.mythsofworlds.registry.ModRegistries.MOB_EFFECTS;

/**
 * Slavic mythology: Nav, the world of spirits and the dead under the roots of the World Tree. The way there is not built
 * but grown: plant an acorn of the World Tree, and a great oak rises with a hollow at its roots that leads down to
 * Nav. Mobs live in {@link SlavicEntities}; biomes, structures and loot are data files generated by
 * tools/gen_slavic_assets.py.
 */
public final class SlavicContent {
    /** Defined in data/mythsofworlds/dimension/nav.json. */
    public static final ResourceKey<Level> NAV =
            ResourceKey.create(Registries.DIMENSION, MythsOfWorlds.id("nav"));
    /** Biomes of Nav (data/mythsofworlds/worldgen/biome). */
    public static final List<String> BIOMES = List.of("dense_forest", "birch_grove", "kikimora_bog", "wild_field",
            "smorodina", "koschei_realm", "okiyan_sea");
    /** Structures of Nav (data/mythsofworlds/worldgen/structure, templates in data/mythsofworlds/structure/slavic). */
    public static final List<String> STRUCTURES = List.of("slavic_village", "baba_yaga_hut", "kapishche", "koschei_oak",
            "solovei_nest", "kalinov_bridge", "koschei_castle");

    // ---- Blocks ----

    /** The hollow at the roots of the World Tree: step inside and you go down to Nav (or back up). */
    public static final DeferredBlock<WorldTreeHollowBlock> WORLD_TREE_HOLLOW = BLOCKS.register("world_tree_hollow",
            () -> new WorldTreeHollowBlock(BlockBehaviour.Properties.of()
                    .mapColor(MapColor.COLOR_BLACK)
                    .noCollission()
                    .strength(-1.0F)
                    .sound(SoundType.WOOD)
                    .lightLevel(state -> 9)
                    .noLootTable()
                    .pushReaction(PushReaction.BLOCK)));

    // ---- Items ----

    /** Acorn of the World Tree: plant it on earth and the oak whose roots reach Nav grows at once. */
    public static final DeferredItem<WorldTreeAcornItem> WORLD_TREE_ACORN = ITEMS.register("world_tree_acorn",
            () -> new WorldTreeAcornItem(new Item.Properties().stacksTo(16).rarity(Rarity.RARE)));

    /** Tales of Boyan, the journal of Nav. */
    public static final DeferredItem<JournalItem> SLAVIC_JOURNAL = ITEMS.register("slavic_journal",
            () -> new JournalItem("slavic", false, new Item.Properties().stacksTo(1)));
    public static final DeferredItem<JournalItem> SLAVIC_JOURNAL_COMPLETE = ITEMS.register("slavic_journal_complete",
            () -> new JournalItem("slavic", true, new Item.Properties().stacksTo(1).rarity(Rarity.EPIC)));

    /** Water of life: heals every wound at once. */
    public static final DeferredItem<HoneyBottleItem> LIVING_WATER = ITEMS.register("living_water",
            () -> new HoneyBottleItem(new Item.Properties().craftRemainder(Items.GLASS_BOTTLE).stacksTo(16).rarity(Rarity.RARE)
                    .food(new FoodProperties.Builder().nutrition(0).saturationModifier(0.0F).alwaysEdible()
                            .effect(new MobEffectInstance(MobEffects.HEAL, 1, 3), 1.0F)
                            .effect(new MobEffectInstance(MobEffects.REGENERATION, 200, 1), 1.0F)
                            .build())));
    /** Dead water: closes wounds and hardens the body (it is poured on the fallen hero before the living water). */
    public static final DeferredItem<HoneyBottleItem> DEAD_WATER = ITEMS.register("dead_water",
            () -> new HoneyBottleItem(new Item.Properties().craftRemainder(Items.GLASS_BOTTLE).stacksTo(16).rarity(Rarity.RARE)
                    .food(new FoodProperties.Builder().nutrition(0).saturationModifier(0.0F).alwaysEdible()
                            .effect(new MobEffectInstance(MobEffects.DAMAGE_RESISTANCE, 1200, 1), 1.0F)
                            .effect(new MobEffectInstance(MobEffects.ABSORPTION, 1200, 2), 1.0F)
                            .build())));
    /** Round loaf of the village feasts. */
    public static final DeferredItem<Item> KARAVAI = ITEMS.registerSimpleItem("karavai", new Item.Properties()
            .food(new FoodProperties.Builder().nutrition(10).saturationModifier(0.9F).build()));
    /** A feather of the Firebird: glows warm, and held in the hand it lights the dusk of Nav (night vision). */
    public static final DeferredItem<Item> FIREBIRD_FEATHER = ITEMS.registerSimpleItem("firebird_feather",
            new Item.Properties().rarity(Rarity.RARE).fireResistant());
    public static final DeferredItem<Item> UPYR_FANG = ITEMS.registerSimpleItem("upyr_fang", new Item.Properties());
    public static final DeferredItem<Item> VOLKOLAK_PELT = ITEMS.registerSimpleItem("volkolak_pelt",
            new Item.Properties().rarity(Rarity.UNCOMMON));
    public static final DeferredItem<Item> ZMEY_SCALE = ITEMS.registerSimpleItem("zmey_scale",
            new Item.Properties().rarity(Rarity.RARE).fireResistant());
    /** Koschei's death lies hidden in a needle, the needle in an egg, the egg in a chest on an oak. */
    public static final DeferredItem<KoscheiEggItem> KOSCHEI_EGG = ITEMS.register("koschei_egg",
            () -> new KoscheiEggItem(new Item.Properties().stacksTo(1).rarity(Rarity.EPIC)));
    /** The needle with the death of Koschei: carry it, and the Deathless can be killed. It breaks when he dies. */
    public static final DeferredItem<Item> KOSCHEI_NEEDLE = ITEMS.registerSimpleItem("koschei_needle",
            new Item.Properties().stacksTo(1).rarity(Rarity.EPIC));

    /** Bulat, the patterned steel of the bogatyrs, forged from ore deep under Nav: the metal of tier II, as strong as
     * diamond. */
    public static final MetalSet BULAT = new MetalSet("bulat", MapColor.COLOR_LIGHT_BLUE, new MetalSet.Stats(
            1700, 8.0F, 3.5F, 16, new int[]{3, 8, 6, 3}, 34, 2.0F, 0.0F, SoundEvents.ARMOR_EQUIP_IRON,
            BlockTags.INCORRECT_FOR_DIAMOND_TOOL));

    /** Kladenets, the sword-of-itself of the bogatyrs: every blow also cuts down the foes around. */
    public static final DeferredItem<KladenetsItem> KLADENETS = ITEMS.register("kladenets",
            () -> new KladenetsItem(BULAT.tier, new Item.Properties().rarity(Rarity.EPIC).fireResistant()
                    .attributes(SwordItem.createAttributes(BULAT.tier, 4, -2.4F))));

    /** Seven-league boots, taken from Solovei the Robber: run like the wind. */
    public static final DeferredHolder<ArmorMaterial, ArmorMaterial> SKOROKHODY_MATERIAL = RelicArmorItem.material("skorokhody",
            ArmorItem.Type.BOOTS, 3, 18, SoundEvents.ARMOR_EQUIP_LEATHER, () -> Ingredient.of(Items.LEATHER), 2.0F, 0.0F);
    public static final DeferredItem<RelicArmorItem> SKOROKHODY = ITEMS.register("skorokhody",
            () -> new RelicArmorItem(SKOROKHODY_MATERIAL, ArmorItem.Type.BOOTS, Mythology.SLAVIC, SlavicRelics::skorokhody,
                    new Item.Properties().durability(ArmorItem.Type.BOOTS.getDurability(30)).rarity(Rarity.EPIC)));
    /** Cap of invisibility from the treasury of Koschei: crouch and no one sees you. */
    public static final DeferredHolder<ArmorMaterial, ArmorMaterial> SHAPKA_MATERIAL = RelicArmorItem.material("shapka_nevidimka",
            ArmorItem.Type.HELMET, 3, 25, SoundEvents.ARMOR_EQUIP_LEATHER, () -> Ingredient.of(Items.LEATHER), 2.0F, 0.0F);
    public static final DeferredItem<RelicArmorItem> SHAPKA_NEVIDIMKA = ITEMS.register("shapka_nevidimka",
            () -> new RelicArmorItem(SHAPKA_MATERIAL, ArmorItem.Type.HELMET, Mythology.SLAVIC, SlavicRelics::shapka,
                    new Item.Properties().durability(ArmorItem.Type.HELMET.getDurability(30)).rarity(Rarity.EPIC)));

    /** The flower of the fern, blooming on Kupala night in the deep forest: raised to the sky, it shows hidden treasure. */
    public static final DeferredBlock<FlowerBlock> FERN_FLOWER = BLOCKS.register("fern_flower",
            () -> new FlowerBlock(MobEffects.LUCK, 10.0F, BlockBehaviour.Properties.of().mapColor(MapColor.COLOR_ORANGE)
                    .noCollission().instabreak().sound(SoundType.GRASS).lightLevel(state -> 10)
                    .offsetType(BlockBehaviour.OffsetType.XZ).pushReaction(PushReaction.DESTROY)));
    public static final DeferredItem<FernFlowerItem> FERN_FLOWER_ITEM = ITEMS.register("fern_flower",
            () -> new FernFlowerItem(FERN_FLOWER.get(), new Item.Properties().rarity(Rarity.RARE)));
    /** The self-laying tablecloth: a feast once a day. */
    public static final DeferredItem<SamobrankaItem> SAMOBRANKA = ITEMS.register("samobranka",
            () -> new SamobrankaItem(new Item.Properties().stacksTo(1).rarity(Rarity.RARE)));
    /** Self-playing gusli: the monsters around break into a dance. */
    public static final DeferredItem<GusliItem> GUSLI = ITEMS.register("gusli",
            () -> new GusliItem(new Item.Properties().durability(48).rarity(Rarity.RARE)));
    /** Baba Yaga's yarn ball: it rolls the way to the next foe. */
    public static final DeferredItem<KlubokItem> KLUBOK = ITEMS.register("klubok",
            () -> new KlubokItem(new Item.Properties().durability(24).rarity(Rarity.UNCOMMON)));
    /** The dance the gusli play into whoever hears them. */
    public static final DeferredHolder<MobEffect, DanceEffect> DANCE = MOB_EFFECTS.register("dance", DanceEffect::new);

    private SlavicContent() {
    }

    /** Called from the mod constructor so the fields above are registered. */
    public static void init() {
    }
}
